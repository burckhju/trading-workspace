FACTS = TypeAdapter(ExtractedProductFacts)
BINDING = TypeAdapter(ProductPriceScaleBinding)


async def latest_document(
    session: AsyncSession,
    *,
    workspace_id: UUID,
    warrant_id: UUID,
    known_at: datetime,
    kind: str = "KID",
) -> ProductReviewDocumentModel | None:
    row: ProductReviewDocumentModel | None = await session.scalar(
        select(ProductReviewDocumentModel)
        .where(
            ProductReviewDocumentModel.workspace_id == workspace_id,
            ProductReviewDocumentModel.warrant_id == warrant_id,
            ProductReviewDocumentModel.kind == kind,
            ProductReviewDocumentModel.recorded_at <= known_at,
        )
        .order_by(ProductReviewDocumentModel.revision_number.desc())
        .limit(1)
    )
    return row


async def record_original_kid(
    session: AsyncSession,
    *,
    workspace_id: UUID,
    warrant_id: UUID,
    source_reference: str,
    document: bytes,
    retrieved_at: datetime,
    now: datetime,
) -> UUID:
    """Internal acquisition command; hashes and bindings are generated by the owner."""
    if not aware(now) or not aware(retrieved_at) or retrieved_at > now:
        raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
    await require_warrant(session, workspace_id=workspace_id, warrant_id=warrant_id, lock=True)
    row = (
        await session.execute(
            select(WarrantModel, WarrantTermsVersionModel, IssuerModel, UnderlyingModel)
            .join(
                WarrantTermsVersionModel,
                WarrantTermsVersionModel.warrant_id == WarrantModel.id,
            )
            .join(IssuerModel, IssuerModel.id == WarrantModel.issuer_id)
            .join(UnderlyingModel, UnderlyingModel.id == WarrantModel.underlying_id)
            .where(
                WarrantModel.id == warrant_id,
                WarrantModel.workspace_id == workspace_id,
                WarrantTermsVersionModel.effective_to.is_(None),
                WarrantTermsVersionModel.created_at <= now,
                WarrantTermsVersionModel.effective_from <= now,
            )
        )
    ).one()
    warrant, terms, issuer, underlying = row
    if source_reference != kid_url(issuer.legal_name, warrant.isin):
        raise ValueError("PRODUCT_DOCUMENT_SOURCE_BINDING_MISMATCH")
    facts = extract_kid(document, isin=warrant.isin, source_url=source_reference)
    issues = list(facts.issues)
    if facts.underlying_isin is not None and facts.underlying_isin != underlying.isin:
        issues.append("PRODUCT_DOCUMENT_UNDERLYING_MISMATCH")
    matches_end = facts.product_end_on is not None and facts.product_end_on == terms.maturity_date
    matches_payment = facts.payment_on is not None and facts.payment_on == terms.maturity_date
    role: CurrentTermsDateRole | None = (
        "PRODUCT_END_AND_PAYMENT"
        if matches_end and matches_payment
        else "PRODUCT_END" if matches_end else "PAYMENT" if matches_payment else None
    )
    dates_ordered = (
        facts.product_end_on is None
        or facts.payment_on is None
        or facts.payment_on >= facts.product_end_on
    )
    if not dates_ordered:
        role = None  # The parser reports the independent, hard document-date contradiction.
    # Existing terms call this field maturity_date; both actual product end and
    # the separately labelled payment date have been stored there. Accept only
    # an exact role match proved by this same original, never an arbitrary later day.
    if (
        dates_ordered
        and (facts.product_end_on is not None or facts.payment_on is not None)
        and role is None
    ):
        issues.append("PRODUCT_DOCUMENT_CURRENT_TERMS_MISMATCH")
    payload = FACTS.dump_python(facts, mode="json")
    payload["issues"] = issues
    payload["current_terms_date_role"] = role
    binding = ProductPriceScaleBinding(
        warrant.id, warrant.isin, warrant.issuer_id, warrant.underlying_id, terms.id
    )
    binding_json = BINDING.dump_python(binding, mode="json")
    digest = hashlib.sha256(document).hexdigest()
    current = await latest_document(
        session,
        workspace_id=workspace_id,
        warrant_id=warrant_id,
        known_at=datetime.max.replace(tzinfo=UTC),
    )
    if current is not None and current.parser_version not in {
        PARSER_VERSION,
        *REPARSEABLE_PARSER_VERSIONS,
    }:
        # Recheck under the product lock: another application may have advanced
        # the parser while this caller was fetching its network original.
        raise ValueError("PRODUCT_DOCUMENT_PARSER_UNSUPPORTED")
    if current is not None and current.recorded_at > now:
        raise ValueError("PRODUCT_DOCUMENT_CLOCK_REGRESSION")
    if current is not None and (
        current.document_sha256 == digest
        and current.binding == binding_json
        and current.facts == payload
        and current.parser_version == PARSER_VERSION
    ):
        return current.id
    revision = ProductReviewDocumentModel(
        id=uuid4(),
        workspace_id=workspace_id,
        warrant_id=warrant_id,
        terms_id=terms.id,
        kind="KID",
        revision_number=current.revision_number + 1 if current else 1,
        recorded_at=now,
        retrieved_at=retrieved_at,
        source_reference=source_reference,
        document_sha256=digest,
        document=document,
        binding=binding_json,
        facts=payload,
        parser_version=PARSER_VERSION,
    )
    session.add(revision)
    await session.flush()
    return revision.id


async def reparse_saved_original_kid(
    session: AsyncSession,
    *,
    workspace_id: UUID,
    warrant_id: UUID,
    now: datetime,
) -> UUID | None:
    """Append a parser upgrade from intact saved bytes without claiming a new fetch.

    The caller commits this local revision before any network work. A changed
    owner binding needs new acquisition, not a silent rebinding of old evidence.
    Unknown/newer parser versions are never downgraded by an older application.
    """
    if not aware(now):
        raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
    await require_warrant(session, workspace_id=workspace_id, warrant_id=warrant_id, lock=True)
    previous = await latest_document(
        session,
        workspace_id=workspace_id,
        warrant_id=warrant_id,
        known_at=datetime.max.replace(tzinfo=UTC),
    )
    if previous is None or previous.parser_version == PARSER_VERSION:
        return None
    if previous.parser_version not in REPARSEABLE_PARSER_VERSIONS:
        raise ValueError("PRODUCT_DOCUMENT_PARSER_UNSUPPORTED")
    if previous.recorded_at > now:
        raise ValueError("PRODUCT_DOCUMENT_CLOCK_REGRESSION")
    if hashlib.sha256(previous.document).hexdigest() != previous.document_sha256:
        raise ValueError("PRODUCT_REVIEW_DOCUMENT_CORRUPT")
    try:
        binding = BINDING.validate_python(previous.binding)
    except ValueError as error:
        raise ValueError("PRODUCT_REVIEW_DOCUMENT_CORRUPT") from error
    if binding.warrant_id != warrant_id or previous.terms_id != binding.current_terms_id:
        raise ValueError("PRODUCT_REVIEW_DOCUMENT_CORRUPT")
    if not await binding_matches(session, workspace_id=workspace_id, binding=binding, known_at=now):
        # Preserve the reader's hard binding conflict and let the ordinary
        # acquisition budget obtain a new original for the changed owner facts.
        return None
    return await record_original_kid(
        session,
        workspace_id=workspace_id,
        warrant_id=warrant_id,
        source_reference=previous.source_reference,
        document=previous.document,
        retrieved_at=previous.retrieved_at,
        now=now,
    )


class ProductReviewEvidenceReader:
    """One caller-owned snapshot, without writes, fetches or last-good fallback."""

    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    async def acquisition_state(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> ProductReviewAcquisitionState | None:
        if not aware(known_at):
            raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
        with self._session.no_autoflush:
            row = await self._session.scalar(
                select(ProductReviewAcquisitionModel).where(
                    ProductReviewAcquisitionModel.workspace_id == workspace_id,
                    ProductReviewAcquisitionModel.warrant_id == warrant_id,
                    ProductReviewAcquisitionModel.attempted_at <= known_at,
                )
            )
            if row is None:
                return None
            return ProductReviewAcquisitionState(
                row.outcome,
                row.attempted_at,
                row.next_attempt_at,
                tuple(row.problems or ()),
            )

    async def _facts(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> tuple[
        ProductReviewDocumentModel | None,
        ProductPriceScaleBinding | None,
        ExtractedProductFacts | None,
        tuple[str, ...],
    ]:
        if not aware(known_at):
            raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
        with self._session.no_autoflush:
            row = await latest_document(
                self._session,
                workspace_id=workspace_id,
                warrant_id=warrant_id,
                known_at=known_at,
            )
            if row is None:
                return None, None, None, ("PRODUCT_REVIEW_DOCUMENT_MISSING",)
            if row.parser_version not in {PARSER_VERSION, *REPARSEABLE_PARSER_VERSIONS}:
                return row, None, None, ("PRODUCT_DOCUMENT_PARSER_UNSUPPORTED",)
            try:
                binding = BINDING.validate_python(row.binding)
                facts = FACTS.validate_python(row.facts)
                if (
                    binding.warrant_id != warrant_id
                    or row.terms_id != binding.current_terms_id
                    or facts.isin != binding.isin
                    or (
                        facts.product_end_on is not None
                        and facts.maturity_on != facts.product_end_on
                    )
                ):
                    raise ValueError("Original document identity metadata disagree")
                if hashlib.sha256(row.document).hexdigest() != row.document_sha256:
                    raise ValueError("Original document integrity")
            except ValueError:
                return row, None, None, ("PRODUCT_REVIEW_DOCUMENT_CORRUPT",)
            reasons = list(facts.issues)
            if not await binding_matches(
                self._session,
                workspace_id=workspace_id,
                binding=binding,
                known_at=known_at,
            ):
                reasons.append("PRODUCT_REVIEW_BINDING_CHANGED")
            underlying = await self._session.get(UnderlyingModel, binding.underlying_id)
            if facts.underlying_isin is not None and (
                underlying is None
                or underlying.workspace_id != workspace_id
                or underlying.isin != facts.underlying_isin
            ):
                reasons.append("PRODUCT_DOCUMENT_UNDERLYING_MISMATCH")
            return row, binding, facts, tuple(dict.fromkeys(reasons))

    async def current_for_review(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> ProductReviewEvidence:
        row, binding, facts, problems = await self._facts(
            workspace_id=workspace_id, warrant_id=warrant_id, known_at=known_at
        )
        reasons = list(problems)
        if facts is not None:
            if facts.currency is None:
                reasons.append("PRODUCT_REVIEW_CURRENCY_UNPROVEN")
            if facts.unit != "CURRENCY_PER_WARRANT":
                reasons.append("PRODUCT_REVIEW_UNIT_UNPROVEN")
        hard_problems = set(reasons) - {
            "PRODUCT_REVIEW_DOCUMENT_MISSING",
            "PRODUCT_REVIEW_CURRENCY_UNPROVEN",
            "PRODUCT_REVIEW_UNIT_UNPROVEN",
            "PRODUCT_DOCUMENT_UNDERLYING_AMBIGUOUS",
        }
        return ProductReviewEvidence(
            workspace_id,
            warrant_id,
            known_at,
            "UNSUITABLE" if hard_problems else "MISSING" if reasons else "AVAILABLE",
            tuple(reasons),
            row.id if row else None,
            row.recorded_at if row else None,
            fingerprint(
                {
                    "revision_id": row.id if row else None,
                    "facts": asdict(facts) if facts else None,
                    "reasons": reasons,
                }
            ),
            binding=binding,
            currency=facts.currency if facts else None,
            unit=facts.unit if facts else None,
            source_reference=row.source_reference if row else None,
            source_document_sha256=row.document_sha256 if row else None,
            reference_venue_mic=facts.reference_venue_mic if facts else None,
            maturity_on=facts.maturity_on if facts else None,
            product_end_on=facts.product_end_on if facts else None,
            product_end_basis=facts.product_end_basis if facts else None,
            payment_on=facts.payment_on if facts else None,
            payment_basis=facts.payment_basis if facts else None,
            payment_qualifier=facts.payment_qualifier if facts else None,
            current_terms_date_role=facts.current_terms_date_role if facts else None,
        )

    async def reference_market_for_review(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> tuple[
        ProductReviewDocumentModel | None,
        ProductPriceScaleBinding | None,
        ExtractedProductFacts | None,
        tuple[str, ...],
    ]:
        # A missing unit does not suppress an independently documented reference market.
        return await self._facts(
            workspace_id=workspace_id, warrant_id=warrant_id, known_at=known_at
        )

    async def deadline_for_review(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> ProductDeadlineEvidence:
        row, binding, facts, problems = await self._facts(
            workspace_id=workspace_id, warrant_id=warrant_id, known_at=known_at
        )
        choice = await read_product_deadline_exit_choice(
            self._session,
            workspace_id=workspace_id,
            warrant_id=warrant_id,
            known_at=known_at,
        )
        listing = await read_product_listing_terms(
            self._session,
            workspace_id=workspace_id,
            warrant_id=warrant_id,
            known_at=known_at,
        )
        # A product date needs no unit, currency, target or underlying-market assumption.
        reasons = [item for item in problems if item != "PRODUCT_DOCUMENT_UNDERLYING_AMBIGUOUS"]
        reasons.extend((*choice.reasons, *listing.reasons))
        if facts is None or facts.maturity_on is None:
            reasons.append("PRODUCT_MATURITY_EVIDENCE_MISSING")
        for component in (choice, listing):
            if (
                component.workspace_id != workspace_id
                or component.warrant_id != warrant_id
                or component.known_at != known_at
                or (
                    component.recorded_at is not None
                    and (not aware(component.recorded_at) or component.recorded_at > known_at)
                )
            ):
                reasons.append("PRODUCT_DEADLINE_COMPONENT_SCOPE_MISMATCH")
        if binding is not None and (
            choice.current_terms_id != binding.current_terms_id
            or (listing.terms_id is not None and listing.terms_id != binding.current_terms_id)
        ):
            reasons.append("PRODUCT_DEADLINE_TERMS_MISMATCH")
        if (
            choice.status == listing.status == "AVAILABLE"
            and choice.exit_venue_mic != listing.venue_mic
        ):
            reasons.append("PRODUCT_LAST_TRADING_DAY_EXIT_VENUE_MISMATCH")
        unique_reasons = tuple(dict.fromkeys(reasons))
        missing = {
            "PRODUCT_REVIEW_DOCUMENT_MISSING",
            "PRODUCT_MATURITY_EVIDENCE_MISSING",
            "PRODUCT_EXIT_LISTING_MISSING",
            "PRODUCT_LAST_TRADING_DAY_EVIDENCE_MISSING",
        }
        hard_problem = bool(set(unique_reasons) - missing) or "UNSUITABLE" in {
            choice.status,
            listing.status,
        }
        status: ReviewEvidenceStatus = (
            "UNSUITABLE" if hard_problem else "MISSING" if unique_reasons else "AVAILABLE"
        )
        clocks = [
            clock
            for clock in (
                row.recorded_at if row else None,
                choice.recorded_at,
                listing.recorded_at,
            )
            if clock is not None and aware(clock)
        ]
        return ProductDeadlineEvidence(
            workspace_id,
            warrant_id,
            known_at,
            status,
            unique_reasons,
            row.id if row else None,
            max(clocks) if clocks else None,
            fingerprint(
                {
                    "kid_revision_id": row.id if row else None,
                    "kid_document_sha256": row.document_sha256 if row else None,
                    "kid_facts": asdict(facts) if facts else None,
                    "exit_choice": choice.fingerprint,
                    "listing_terms": listing.fingerprint,
                    "reasons": unique_reasons,
                }
            ),
            terms_id=binding.current_terms_id if binding else None,
            maturity_on=facts.maturity_on if facts else None,
            last_trading_on=listing.last_trading_on,
            exit_listing_id=choice.exit_listing_id,
            exit_venue_mic=choice.exit_venue_mic,
            source_reference=listing.source_reference,
            verification="CURRENT_KID_AND_USER_SUPPLIED_LISTING_ORIGINAL_NOT_INDEPENDENT_VERIFICATION",
            product_document_revision_id=row.id if row else None,
            listing_terms_revision_id=listing.revision_id,
            exit_choice_revision_id=choice.revision_id,
            product_document_source_reference=row.source_reference if row else None,
            product_end_on=facts.product_end_on if facts else None,
            product_end_basis=facts.product_end_basis if facts else None,
            payment_on=facts.payment_on if facts else None,
            payment_basis=facts.payment_basis if facts else None,
            payment_qualifier=facts.payment_qualifier if facts else None,
            current_terms_date_role=facts.current_terms_date_role if facts else None,
        )
