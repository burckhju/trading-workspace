FACTS = TypeAdapter(ExtractedProductFacts)
BINDING = TypeAdapter(ProductPriceScaleBinding)


async def latest_document(
    session: AsyncSession,
    *,
    workspace_id: UUID,
    warrant_id: UUID,
    known_at: datetime,
    kind: str = "KID",
) -> ProductReviewDocumentModel | None:
    row: ProductReviewDocumentModel | None = await session.scalar(
        select(ProductReviewDocumentModel)
        .where(
            ProductReviewDocumentModel.workspace_id == workspace_id,
            ProductReviewDocumentModel.warrant_id == warrant_id,
            ProductReviewDocumentModel.kind == kind,
            ProductReviewDocumentModel.recorded_at <= known_at,
        )
        .order_by(ProductReviewDocumentModel.revision_number.desc())
        .limit(1)
    )
    return row


async def record_original_kid(
    session: AsyncSession,
    *,
    workspace_id: UUID,
    warrant_id: UUID,
    source_reference: str,
    document: bytes,
    retrieved_at: datetime,
    now: datetime,
) -> UUID:
    """Internal acquisition command; hashes and bindings are generated by the owner."""
    if not aware(now) or not aware(retrieved_at) or retrieved_at > now:
        raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
    await require_warrant(session, workspace_id=workspace_id, warrant_id=warrant_id, lock=True)
    row = (
        await session.execute(
            select(WarrantModel, WarrantTermsVersionModel, IssuerModel, UnderlyingModel)
            .join(
                WarrantTermsVersionModel,
                WarrantTermsVersionModel.warrant_id == WarrantModel.id,
            )
            .join(IssuerModel, IssuerModel.id == WarrantModel.issuer_id)
            .join(UnderlyingModel, UnderlyingModel.id == WarrantModel.underlying_id)
            .where(
                WarrantModel.id == warrant_id,
                WarrantModel.workspace_id == workspace_id,
                WarrantTermsVersionModel.effective_to.is_(None),
                WarrantTermsVersionModel.created_at <= now,
                WarrantTermsVersionModel.effective_from <= now,
            )
        )
    ).one()
    warrant, terms, issuer, underlying = row
    if source_reference != kid_url(issuer.legal_name, warrant.isin):
        raise ValueError("PRODUCT_DOCUMENT_SOURCE_BINDING_MISMATCH")
    facts = extract_kid(document, isin=warrant.isin, source_url=source_reference)
    issues = list(facts.issues)
    if facts.underlying_isin is not None and facts.underlying_isin != underlying.isin:
        issues.append("PRODUCT_DOCUMENT_UNDERLYING_MISMATCH")
    if facts.maturity_on is not None and facts.maturity_on != terms.maturity_date:
        issues.append("PRODUCT_DOCUMENT_CURRENT_TERMS_MISMATCH")
    payload = FACTS.dump_python(facts, mode="json")
    payload["issues"] = issues
    binding = ProductPriceScaleBinding(
        warrant.id, warrant.isin, warrant.issuer_id, warrant.underlying_id, terms.id
    )
    binding_json = BINDING.dump_python(binding, mode="json")
    digest = hashlib.sha256(document).hexdigest()
    current = await latest_document(
        session,
        workspace_id=workspace_id,
        warrant_id=warrant_id,
        known_at=datetime.max.replace(tzinfo=UTC),
    )
    if current is not None and current.recorded_at > now:
        raise ValueError("PRODUCT_DOCUMENT_CLOCK_REGRESSION")
    if current is not None and (
        current.document_sha256 == digest
        and current.binding == binding_json
        and current.facts == payload
        and current.parser_version == PARSER_VERSION
    ):
        return current.id
    revision = ProductReviewDocumentModel(
        id=uuid4(),
        workspace_id=workspace_id,
        warrant_id=warrant_id,
        terms_id=terms.id,
        kind="KID",
        revision_number=current.revision_number + 1 if current else 1,
        recorded_at=now,
        retrieved_at=retrieved_at,
        source_reference=source_reference,
        document_sha256=digest,
        document=document,
        binding=binding_json,
        facts=payload,
        parser_version=PARSER_VERSION,
    )
    session.add(revision)
    await session.flush()
    return revision.id


class ProductReviewEvidenceReader:
    """One caller-owned snapshot, without writes, fetches or last-good fallback."""

    def __init__(self, session: AsyncSession) -> None:
        self._session = session

    async def acquisition_state(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> ProductReviewAcquisitionState | None:
        if not aware(known_at):
            raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
        with self._session.no_autoflush:
            row = await self._session.scalar(
                select(ProductReviewAcquisitionModel).where(
                    ProductReviewAcquisitionModel.workspace_id == workspace_id,
                    ProductReviewAcquisitionModel.warrant_id == warrant_id,
                    ProductReviewAcquisitionModel.attempted_at <= known_at,
                )
            )
            if row is None:
                return None
            return ProductReviewAcquisitionState(
                row.outcome, row.attempted_at, row.next_attempt_at, tuple(row.problems or ())
            )

    async def _facts(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> tuple[
        ProductReviewDocumentModel | None,
        ProductPriceScaleBinding | None,
        ExtractedProductFacts | None,
        tuple[str, ...],
    ]:
        if not aware(known_at):
            raise ValueError("PRODUCT_DOCUMENT_CLOCK_INVALID")
        with self._session.no_autoflush:
            row = await latest_document(
                self._session,
                workspace_id=workspace_id,
                warrant_id=warrant_id,
                known_at=known_at,
            )
            if row is None:
                return None, None, None, ("PRODUCT_REVIEW_DOCUMENT_MISSING",)
            try:
                binding = BINDING.validate_python(row.binding)
                facts = FACTS.validate_python(row.facts)
                if (
                    binding.warrant_id != warrant_id
                    or row.terms_id != binding.current_terms_id
                    or facts.isin != binding.isin
                ):
                    raise ValueError("Original document identity metadata disagree")
                if hashlib.sha256(row.document).hexdigest() != row.document_sha256:
                    raise ValueError("Original document integrity")
            except ValueError:
                return row, None, None, ("PRODUCT_REVIEW_DOCUMENT_CORRUPT",)
            reasons = list(facts.issues)
            if not await binding_matches(
                self._session,
                workspace_id=workspace_id,
                binding=binding,
                known_at=known_at,
            ):
                reasons.append("PRODUCT_REVIEW_BINDING_CHANGED")
            underlying = await self._session.get(UnderlyingModel, binding.underlying_id)
            if facts.underlying_isin is not None and (
                underlying is None
                or underlying.workspace_id != workspace_id
                or underlying.isin != facts.underlying_isin
            ):
                reasons.append("PRODUCT_DOCUMENT_UNDERLYING_MISMATCH")
            return row, binding, facts, tuple(dict.fromkeys(reasons))

    async def current_for_review(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> ProductReviewEvidence:
        row, binding, facts, problems = await self._facts(
            workspace_id=workspace_id, warrant_id=warrant_id, known_at=known_at
        )
        reasons = list(problems)
        if facts is not None:
            if facts.currency is None:
                reasons.append("PRODUCT_REVIEW_CURRENCY_UNPROVEN")
            if facts.unit != "CURRENCY_PER_WARRANT":
                reasons.append("PRODUCT_REVIEW_UNIT_UNPROVEN")
        hard_problems = set(reasons) - {
            "PRODUCT_REVIEW_DOCUMENT_MISSING",
            "PRODUCT_REVIEW_CURRENCY_UNPROVEN",
            "PRODUCT_REVIEW_UNIT_UNPROVEN",
            "PRODUCT_DOCUMENT_UNDERLYING_AMBIGUOUS",
        }
        return ProductReviewEvidence(
            workspace_id,
            warrant_id,
            known_at,
            "UNSUITABLE" if hard_problems else "MISSING" if reasons else "AVAILABLE",
            tuple(reasons),
            row.id if row else None,
            row.recorded_at if row else None,
            fingerprint(
                {
                    "revision_id": row.id if row else None,
                    "facts": asdict(facts) if facts else None,
                    "reasons": reasons,
                }
            ),
            binding=binding,
            currency=facts.currency if facts else None,
            unit=facts.unit if facts else None,
            source_reference=row.source_reference if row else None,
            source_document_sha256=row.document_sha256 if row else None,
            reference_venue_mic=facts.reference_venue_mic if facts else None,
            maturity_on=facts.maturity_on if facts else None,
        )

    async def reference_market_for_review(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> tuple[
        ProductReviewDocumentModel | None,
        ProductPriceScaleBinding | None,
        ExtractedProductFacts | None,
        tuple[str, ...],
    ]:
        # A missing unit does not suppress an independently documented reference market.
        return await self._facts(
            workspace_id=workspace_id, warrant_id=warrant_id, known_at=known_at
        )

    async def deadline_for_review(
        self,
        *,
        workspace_id: UUID,
        warrant_id: UUID,
        known_at: datetime,
    ) -> ProductDeadlineEvidence:
        # The explicit personal exit-listing owner is composed in the deadline increment.
        row, binding, facts, problems = await self._facts(
            workspace_id=workspace_id, warrant_id=warrant_id, known_at=known_at
        )
        reasons = (
            *problems,
            "PRODUCT_EXIT_LISTING_MISSING",
            "PRODUCT_LAST_TRADING_DAY_UNVERIFIED",
        )
        return ProductDeadlineEvidence(
            workspace_id,
            warrant_id,
            known_at,
            "MISSING" if row is None else "UNSUITABLE",
            reasons,
            row.id if row else None,
            row.recorded_at if row else None,
            fingerprint({"revision_id": row.id if row else None, "reasons": reasons}),
            terms_id=binding.current_terms_id if binding else None,
            maturity_on=facts.maturity_on if facts else None,
            source_reference=row.source_reference if row else None,
        )
